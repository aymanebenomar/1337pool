#include <unistd.h>

void	ft_putnbr(int nb)
{
	char	s[10];
	long	n;
	int		i;

	i = 0;
	n = nb;
	if (n == 0)
	{
		write(1, "0", 1);
		return ;
	}
	if (n < 0)
	{
		write(1, "-", 1);
		n = -n;
	}
	while (n > 0)
	{
		s[i++] = (n % 10) + '0';
		n /= 10;
	}
	while (i > 0)
		write(1, &s[--i], 1);
}
