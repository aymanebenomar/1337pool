#include <unistd.h>

void	ft_putnbr(int nb)
{
	long	n;
	int		i;
	char	nums[10];

	n = nb;
	i = 0;
	if (n < 0)
	{
		write(1, "-", 1);
		n = -n;
	}
	if (n == 0)
		write(1, "0", 1);
	while (n != 0)
	{
		nums[i++] = (n % 10) + '0';
		n /= 10;
	}
	while (i > 0)
		write(1, &nums[--i], 1);
}
